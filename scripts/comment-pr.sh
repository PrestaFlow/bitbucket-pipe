#!/usr/bin/env bash
#
# Post (or update) a summary comment on the current pull request.
# Bitbucket Cloud API: /2.0/repositories/{workspace}/{repo}/pullrequests/{id}/comments
# Auth: repository access token with `pullrequest:write` (Bearer). Optional — if the
# token isn't provided we warn once and exit 0; PR comments are a nice-to-have.
#
# Idempotency: we look for a marker string (<!-- prestaflow-run:<pk> --> or a fallback)
# inside existing comments and PUT to update the first match, otherwise POST.
#
set -euo pipefail

DEFAULT="false"
if [ -n "${BITBUCKET_PR_ID:-}" ]; then DEFAULT="true"; fi

MODE="${PRESTAFLOW_PR_COMMENT:-}"
if [ -z "$MODE" ]; then MODE="$DEFAULT"; fi

if [ "$MODE" != "true" ]; then
  echo "comment-pr: disabled (pr_comment=$MODE) — skipping"
  exit 0
fi

if [ -z "${BITBUCKET_PR_ID:-}" ]; then
  echo "comment-pr: not a pull-request pipeline — skipping"
  exit 0
fi

if [ -z "${BITBUCKET_ACCESS_TOKEN:-}" ]; then
  echo "comment-pr: BITBUCKET_ACCESS_TOKEN not set — cannot post PR comments."
  echo "comment-pr:   Create a Repository Access Token with 'pullrequest:write' and expose it as BITBUCKET_ACCESS_TOKEN."
  echo "comment-pr:   Skipping (warning, not a failure)."
  exit 0
fi

WORKSPACE_SLUG="${BITBUCKET_WORKSPACE:-}"
REPO_SLUG="${BITBUCKET_REPO_SLUG:-}"
PR_ID="${BITBUCKET_PR_ID}"
API="https://api.bitbucket.org/2.0/repositories/${WORKSPACE_SLUG}/${REPO_SLUG}/pullrequests/${PR_ID}/comments"

RESULTS=""
for c in tests/prestaflow/results.json prestaflow/results.json; do
  if [ -f "${PRESTAFLOW_WORKSPACE:-$PWD}/$c" ]; then RESULTS="${PRESTAFLOW_WORKSPACE:-$PWD}/$c"; break; fi
done

REPORT_URL=""
REPORT_ID=""
if [ -f "${PRESTAFLOW_WORKSPACE:-$PWD}/prestaflow.env" ]; then
  # shellcheck disable=SC1091
  . "${PRESTAFLOW_WORKSPACE:-$PWD}/prestaflow.env" || true
  REPORT_URL="${PRESTAFLOW_REPORT_URL:-}"
  REPORT_ID="${PRESTAFLOW_REPORT_ID:-}"
fi

if [ -n "$RESULTS" ]; then
  STATS_JSON=$(jq '
    def tonum(x): (x // 0 | tonumber? // 0);
    def sfrom(s): s as $s |
      { name: ($s.suite // ""),
        passed: ($s.stats.passes | tonum(.)),
        failed: ($s.stats.failures | tonum(.)),
        skipped: (($s.stats.skips | tonum(.)) + ($s.stats.skippeds | tonum(.))),
        todos: ($s.stats.todos | tonum(.)),
        durationMs: ($s.stats.time | tonum(.)),
        failures: [ ($s.tests // [])[] | select(.state == "fail") | {
          suite: ($s.suite // ""),
          title: (.title // ""),
          message: ((.expect.fail // [])[0] // ""),
          file: (.file // ""),
          line: (.line | tonum(.))
        }]
      };
    if type == "object" and (.suites | type == "array") then
      [ .suites[] | sfrom(.) ]
    elif type == "object" and (.stats) then
      [ sfrom(.) ]
    else
      []
    end
    | { suites: [ .[] | {name, passed, failed, skipped, durationMs} ],
        failures: [ .[].failures[] ],
        passed: ([.[].passed] | add // 0),
        failed: ([.[].failed] | add // 0),
        skipped: ([.[].skipped] | add // 0),
        todos: ([.[].todos] | add // 0),
        durationMs: ([.[].durationMs] | add // 0) }
    | .total = (.passed + .failed + .skipped + .todos)
  ' "$RESULTS")
else
  STATS_JSON='{"suites":[],"failures":[],"passed":0,"failed":0,"skipped":0,"todos":0,"durationMs":0,"total":0}'
fi

PASSED=$(echo "$STATS_JSON" | jq -r '.passed')
FAILED=$(echo "$STATS_JSON" | jq -r '.failed')
SKIPPED=$(echo "$STATS_JSON" | jq -r '.skipped')
TOTAL=$(echo "$STATS_JSON" | jq -r '.total')
DURATION_MS=$(echo "$STATS_JSON" | jq -r '.durationMs')

format_duration() {
  local ms="$1"
  local s=$(( (ms + 500) / 1000 ))
  if [ $s -lt 60 ]; then echo "${s}s"; return; fi
  local m=$(( s / 60 )); local r=$(( s % 60 ))
  printf "%dm %02ds" "$m" "$r"
}

DURATION_HUMAN=$(format_duration "$DURATION_MS")

PROJECT_KEY="${PRESTAFLOW_PROJECT_ID:-}"
if [ -z "$PROJECT_KEY" ]; then
  MARKER='<!-- prestaflow-report -->'
else
  MARKER="<!-- prestaflow-run:${PROJECT_KEY} -->"
fi

SHORT_SHA=$(printf '%s' "${BITBUCKET_COMMIT:-}" | cut -c1-7)
FOOTER="<sub>Generated by [PrestaFlow/bitbucket-pipe](https://github.com/PrestaFlow/bitbucket-pipe) · commit \`${SHORT_SHA}\`</sub>"

META_PARTS=()
if [ -n "${PRESTAFLOW_SUITES:-}" ]; then
  QUOTED=$(printf '%s' "$PRESTAFLOW_SUITES" | awk -F, '{for(i=1;i<=NF;i++){gsub(/^[ \t]+|[ \t]+$/,"",$i); if($i!="") printf "%s`%s`", (i>1?", ":""), $i}}')
  META_PARTS+=("Suites: $QUOTED")
fi
if [ "${PRESTAFLOW_FLASHLIGHT:-false}" = "true" ] && [ -n "${PRESTAFLOW_FLASHLIGHT_TAG:-}" ]; then
  META_PARTS+=("PS \`${PRESTAFLOW_FLASHLIGHT_TAG}\`")
fi
META_LINE=""
if [ ${#META_PARTS[@]} -gt 0 ]; then
  META_LINE=$(printf ' · %s' "${META_PARTS[@]}"); META_LINE="${META_LINE:3}"
fi

SUITE_TABLE=""
SUITE_COUNT=$(echo "$STATS_JSON" | jq -r '.suites | length')
if [ "$SUITE_COUNT" -gt 1 ]; then
  ROWS=$(echo "$STATS_JSON" | jq -r '
    .suites[] |
    "| " + .name + " | " + (.passed|tostring) + " | " + (.failed|tostring) + " | " + (.durationMs|tostring) + "ms |"')
  HUMAN_ROWS=""
  while IFS= read -r row; do
    ms=$(echo "$row" | awk -F' \\| ' '{gsub("ms \\|","",$5); print $5}')
    hum=$(format_duration "${ms:-0}")
    HUMAN_ROWS+="${row/${ms}ms |/${hum} |}\n"
  done <<< "$ROWS"
  SUITE_TABLE="| Suite | Passed | Failed | Duration |
|-------|:------:|:------:|:--------:|
$(printf '%b' "$HUMAN_ROWS")"
fi

if [ "$FAILED" = "0" ]; then
  BODY="$MARKER

**${TOTAL} tests passed in ${DURATION_HUMAN}**
"
  [ -n "$SUITE_TABLE" ] && BODY="${BODY}
${SUITE_TABLE}
"
  [ -n "$META_LINE" ] && BODY="${BODY}
${META_LINE}
"
  [ -n "$REPORT_URL" ] && BODY="${BODY}
[View full report](${REPORT_URL})
"
  BODY="${BODY}
${FOOTER}"
else
  MAX_FAILURES=20
  FAILURE_COUNT=$(echo "$STATS_JSON" | jq -r '.failures | length')
  EXTRA=$(( FAILURE_COUNT - MAX_FAILURES )); [ $EXTRA -lt 0 ] && EXTRA=0

  FAILURE_DETAILS=$(echo "$STATS_JSON" | jq -r --argjson max "$MAX_FAILURES" '
    .failures[:$max] | map(
      "**" + .suite + " / " + .title + "**\n> " +
      (if (.message | length) > 200 then (.message[0:200] + "…") else .message end) +
      (if .file != "" then ("\n> `" + .file + ":" + (.line|tostring) + "`") else "" end)
    ) | join("\n\n")')
  if [ "$EXTRA" -gt 0 ]; then
    FAILURE_DETAILS="${FAILURE_DETAILS}

… +${EXTRA} more failed. View full run for the complete list."
  fi

  BODY="$MARKER

**Result: ${FAILED} failures out of ${TOTAL} tests**

| Passed | Failed | Skipped | Duration |
|--------|--------|---------|----------|
| ${PASSED} | ${FAILED} | ${SKIPPED} | ${DURATION_HUMAN} |
"
  [ -n "$SUITE_TABLE" ] && BODY="${BODY}
${SUITE_TABLE}
"
  [ -n "$META_LINE" ] && BODY="${BODY}
${META_LINE}
"
  BODY="${BODY}
<details>
<summary>Failure details (${FAILED})</summary>

${FAILURE_DETAILS}

</details>
"
  [ -n "$REPORT_URL" ] && BODY="${BODY}
[View full report](${REPORT_URL})
"
  BODY="${BODY}
${FOOTER}"
fi

AUTH_HEADER="Authorization: Bearer ${BITBUCKET_ACCESS_TOKEN}"

find_existing_comment_id() {
  # Paginate a few times through the top-level comments, looking for our marker.
  local url="${API}?pagelen=100"
  local page=0
  while [ -n "$url" ] && [ "$page" -lt 5 ]; do
    local resp
    resp=$(curl -sS -H "$AUTH_HEADER" "$url") || return 0
    local id
    id=$(echo "$resp" | jq -r --arg m1 '<!-- prestaflow-run:' --arg m2 '<!-- prestaflow-report -->' '
      (.values // []) | map(select(((.content.raw // "") | (startswith($m1) or startswith($m2))) and (.deleted != true))) | .[0].id // empty')
    if [ -n "$id" ]; then echo "$id"; return 0; fi
    url=$(echo "$resp" | jq -r '.next // empty')
    page=$((page + 1))
  done
}

EXISTING=$(find_existing_comment_id || true)

PAYLOAD=$(jq -n --arg body "$BODY" '{content: {raw: $body}}')

if [ -n "$EXISTING" ]; then
  echo "comment-pr: updating existing comment #$EXISTING"
  curl -sS -X PUT \
    -H "$AUTH_HEADER" \
    -H "Content-Type: application/json" \
    -d "$PAYLOAD" \
    "${API}/${EXISTING}" \
    -o /dev/null -w 'http=%{http_code}\n'
else
  echo "comment-pr: creating new comment on PR #${PR_ID}"
  curl -sS -X POST \
    -H "$AUTH_HEADER" \
    -H "Content-Type: application/json" \
    -d "$PAYLOAD" \
    "${API}" \
    -o /dev/null -w 'http=%{http_code}\n'
fi
